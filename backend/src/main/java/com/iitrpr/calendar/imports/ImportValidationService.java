package com.iitrpr.calendar.imports;

import com.iitrpr.calendar.domain.CourseSlot;
import com.iitrpr.calendar.domain.CourseSlotRepository;
import com.iitrpr.calendar.domain.SlotTime;
import com.iitrpr.calendar.domain.SlotTimeRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import java.time.LocalTime;
import java.util.List;
import java.util.Map;

@Service
public class ImportValidationService {

    @Autowired
    private CourseSlotRepository courseSlotRepository;

    @Autowired
    private SlotTimeRepository slotTimeRepository;

    /**
     * Rule 1: Dynamic Detection of Grid vs Enrolment sheets.
     */
    public void detectSheetTypeMismatch(String requestedKind, Map<String, String> resolvedSchemaMap, ValidationReport report) {
        boolean hasEmail = resolvedSchemaMap.containsKey("email");
        boolean hasTimeRange = resolvedSchemaMap.containsKey("time_range");

        if ("enrolment".equalsIgnoreCase(requestedKind) && !hasEmail) {
            report.setBlockedReason("ENROLMENT");
            report.addGlobalError("Sheet Structure Anomaly: Enrolment uploads require a valid student email address column mapping.");
        }
        
        if ("classes".equalsIgnoreCase(requestedKind) && !hasTimeRange) {
            report.setBlockedReason("GRID");
            report.addGlobalError("Sheet Structure Anomaly: Timetable class uploads require a valid slot timing range column.");
        }
    }

    /**
     * Rule 2: Skipping Summary Rows.
     */
    public boolean isSummaryRow(Map<String, String> rowData) {
        if (rowData == null || rowData.isEmpty()) return true;
        
        for (String val : rowData.values()) {
            if (val != null) {
                String cleanVal = val.toLowerCase().trim();
                if (cleanVal.startsWith("total") || cleanVal.contains("generated by") || cleanVal.contains("count:")) {
                    return true;
                }
            }
        }
        
        return !rowData.containsKey("course_code") && !rowData.containsKey("email");
    }

    /**
     * Rule 3: Timetable Clash Checking.
     */
    public String checkTimetableClash(String courseCode, String slotCode, Short weekday, LocalTime start, LocalTime end) {
        if (weekday == null || start == null || end == null) return null;

        // Fetch current active allocations matching that day
        List<SlotTime> activeSlots = slotTimeRepository.findByWeekday(weekday);
        
        for (SlotTime existingSlot : activeSlots) {
            // Overlap check formula: (StartA < EndB) AND (EndA > StartB)
            if (start.isBefore(existingSlot.getEndTime()) && end.isAfter(existingSlot.getStartTime())) {
                
                // Fetch course slot mappings using the repository bean tool
                List<CourseSlot> owners = courseSlotRepository.findBySlotCode(existingSlot.getSlotCode());
                
                // ✅ FIXED: Safely reads getCourseCode() camelCase property mapping bounds
                String details = owners.isEmpty() ? "Another Subject" : owners.get(0).getCourseCode();
                
                return String.format("Schedule Conflict: Slot %s (%s-%s) clashes with existing Course %s via Slot %s.",
                        slotCode, start, end, details, existingSlot.getSlotCode());
            }
        }
        return null;
    }
}
